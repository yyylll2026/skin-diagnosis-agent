def build_vision_user_prompt(user_text: str = "") -> str:
    """组合视觉分析的用户侧提示词。

    Args:
        user_text: 用户随图片一起提交的文字描述，可为空。

    Returns:
        拼接好的用户提示词。
    """
    base = "请分析这张皮肤照片，按约定的 JSON 结构输出结果。"
    if user_text.strip():
        return (
            f"{base}\n\n"
            f"用户补充的文字描述（仅作参考，不可当作确诊依据，也不要盲从）：\n"
            f"{user_text.strip()}"
        )
    return base


