"""初始 schema：建出全部业务表、索引，并给老库补列。

Revision ID: 0001_initial
Revises:
Create Date: 2026-10-03

## 为什么迁移脚本里要带「补列」逻辑

这个迁移要同时服务三种库：

1. **全新的空库**（新克隆、新容器）—— 全部 `CREATE TABLE` 建出来即可；
2. **历史上的 SQLite 库**（`backend/data/app.db`）—— 老版本用
   `CREATE TABLE IF NOT EXISTS` 建表，所以「表已存在但缺列」是常态，
   例如 `sessions` 早期没有 `user_id`。`IF NOT EXISTS` 对已存在的表是空操作，
   **不会补列**，必须显式 `ALTER TABLE`；
3. **PostgreSQL 新库** —— 与第 1 种走同一套语句，只把自增主键换成 identity 列。

把补列写进迁移而不是留在运行时代码里，好处是 schema 只有一个来源：
`MetadataStore` 启动时只负责「升级到 head」，不再执行任何 DDL。

## 顺序很关键

`idx_sessions_user` 引用 `user_id`，必须排在补列之后。
早期版本把这条索引放在建表脚本里，结果在全新库上全绿、在老库上直接报
`no such column: user_id`——**只测「全新建库」是测不出这类问题的**，
所以 `tests/test_db_migration.py` 专门构造老格式库来覆盖它。
"""

