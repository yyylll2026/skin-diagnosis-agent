def _auto_pk(dialect: str) -> str:
    """自增主键的方言写法。

    SQLite 用 `AUTOINCREMENT`（且必须紧跟 `INTEGER PRIMARY KEY`）；
    PostgreSQL 用 identity 列。用 `BIGINT` 而不是 `INTEGER`：
    消息与审计日志是只增不减的表，32 位在长期运行后有溢出的可能。
    """
    if dialect == "sqlite":
        return "INTEGER PRIMARY KEY AUTOINCREMENT"
    return "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"


