def _index_statements() -> list[str]:
    """索引语句。

    全部排在「补列」之后执行：其中 `idx_sessions_user` 引用的是老库上
    后补出来的 `user_id`，顺序颠倒会在老库上直接失败。
    """
    return [
        "CREATE INDEX IF NOT EXISTS idx_messages_session ON messages(session_id, id)",
        "CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id, updated_at DESC)",
        """
        CREATE INDEX IF NOT EXISTS idx_health_records_user_date
            ON health_records(user_id, recorded_on DESC, created_at DESC)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_analysis_tasks_user_created
            ON analysis_tasks(user_id, created_at DESC)
        """,
        "CREATE INDEX IF NOT EXISTS idx_analysis_tasks_session ON analysis_tasks(session_id)",
        "CREATE INDEX IF NOT EXISTS idx_auth_sessions_user ON auth_sessions(user_id)",
        "CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(id DESC)",
    ]


def _column_exists(bind: sa.Connection, table: str, column: str) -> bool:
    """表里是否已有某列。

    表不存在时返回 True（跳过补列）：说明它是被本次迁移刚建出来的，
    建表语句里已经带了该列。

    离线模式（``alembic upgrade head --sql``）下没有真实连接可反射，
    统一按「需要补列」处理——生成出来的脚本是给人审阅/手工执行的，
    把 ALTER 显式写出来比悄悄省略更容易发现问题。
    """
    if alembic_context.is_offline_mode():
        return False
    inspector = sa.inspect(bind)
    if table not in inspector.get_table_names():
        return True
    return column in {item["name"] for item in inspector.get_columns(table)}


def upgrade() -> None:
    """升级到本版本。"""
    bind = op.get_bind()
    dialect = bind.dialect.name

    for statement in _table_statements(dialect):
        op.execute(sa.text(statement))

    # 老库补列：`CREATE TABLE IF NOT EXISTS` 不会给已存在的表加列
    if not _column_exists(bind, "sessions", "user_id"):
        op.execute(sa.text("ALTER TABLE sessions ADD COLUMN user_id TEXT NOT NULL DEFAULT ''"))

    for statement in _index_statements():
        op.execute(sa.text(statement))


def downgrade() -> None:
    """回滚：删掉本迁移建出的全部对象。"""
    for table in (
        "audit_logs",
        "auth_sessions",
        "users",
        "analysis_tasks",
        "health_records",
        "clarifications",
        "messages",
        "sessions",
        "documents",
    ):
        op.execute(sa.text(f"DROP TABLE IF EXISTS {table}"))


